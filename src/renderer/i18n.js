  // Étapes de finition (« recadrage 9:16 », « vitesse ×1,5 », « taille < 10 Mo »…)
  function stepName(s) {
    let m;
    if ((m = s.match(/^recadrage (.+)$/))) return "cropping " + m[1];
    if ((m = s.match(/^fond flou (.+)$/))) return "blurred background " + m[1];
    if ((m = s.match(/^vitesse ×(.+)$/))) return "speed ×" + m[1].replace(",", ".");
    if ((m = s.match(/^taille < (\d+) Mo$/))) return `size < ${m[1]} MB`;
    return EN[s] || s;
  }

  function tr(s) {
    if (typeof s !== "string" || !s) return s;
    if (s.includes("\n")) return s.split("\n").map(tr).join("\n");
    const key = s.replace(/\s+/g, " ");
    if (Object.prototype.hasOwnProperty.call(EN, key)) return EN[key];
    const k = key.trim();
    if (k !== key && Object.prototype.hasOwnProperty.call(EN, k)) return key.replace(k, EN[k]);
    for (const [re, to] of RULES) if (re.test(key)) return key.replace(re, to);
    return s;
  }

  // Traduit toute la page : textes (entre balises), bulles d'aide, textes indicatifs, étiquettes d'accessibilité
  function translatePage(doc) {
    doc.documentElement.lang = "en";
    const walker = doc.createTreeWalker(doc.body, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    for (const n of nodes) {
      const raw = n.nodeValue, text = raw.replace(/\s+/g, " ").trim();
      if (!text || !/[A-Za-zÀ-ÿ]/.test(text)) continue;
      const t = tr(text);
      if (t !== text) n.nodeValue = (/^\s/.test(raw) ? " " : "") + t + (/\s$/.test(raw) ? " " : "");
    }
    for (const el of doc.querySelectorAll("[title], [placeholder], [aria-label]")) {
      for (const a of ["title", "placeholder", "aria-label"]) if (el.hasAttribute(a)) el.setAttribute(a, tr(el.getAttribute(a)));
    }
  }

  window.VC_I18N = Object.freeze({ tr, translatePage });
